CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_level varchar(20) NOT NULL,
    age integer NOT NULL,
    gender varchar(10) NOT NULL,
    goal varchar(20) NOT NULL,
    height_cm double precision NOT NULL,
    nickname varchar(40) NOT NULL,
    weekly_training_frequency integer NOT NULL,
    weight_kg double precision NOT NULL,
    email varchar(254),
    password_hash varchar(100),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT users_activity_level_check CHECK (
        activity_level IN ('SEDENTARY', 'LIGHT', 'MODERATE', 'VERY_ACTIVE', 'EXTRA_ACTIVE')
    ),
    CONSTRAINT users_gender_check CHECK (gender IN ('MALE', 'FEMALE')),
    CONSTRAINT users_goal_check CHECK (goal IN ('FAT_LOSS', 'MAINTAIN', 'LEAN_BULK'))
);

CREATE TABLE nutrition_targets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bmr integer NOT NULL,
    calories integer NOT NULL,
    carbsg integer NOT NULL,
    effective_date date NOT NULL,
    fatg integer NOT NULL,
    proteing integer NOT NULL,
    tdee integer NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT fk_nutrition_targets_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE foods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calories_per100g numeric(8, 2) NOT NULL,
    carbs_per100g numeric(6, 2) NOT NULL,
    fat_per100g numeric(6, 2) NOT NULL,
    name varchar(100) NOT NULL,
    protein_per100g numeric(6, 2) NOT NULL,
    CONSTRAINT uk_foods_name UNIQUE (name)
);

CREATE TABLE food_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eaten_at timestamp(6) without time zone NOT NULL,
    grams numeric(8, 2) NOT NULL,
    meal_type varchar(20) NOT NULL,
    food_id bigint NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT food_logs_meal_type_check CHECK (
        meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK')
    ),
    CONSTRAINT fk_food_logs_food FOREIGN KEY (food_id) REFERENCES foods (id),
    CONSTRAINT fk_food_logs_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_food_logs_user_eaten_at ON food_logs (user_id, eaten_at);

CREATE TABLE weight_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    recorded_date date NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    weight_kg numeric(5, 2) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT uk_weight_logs_user_date UNIQUE (user_id, recorded_date),
    CONSTRAINT fk_weight_logs_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE training_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    name varchar(100) NOT NULL,
    weekly_frequency integer NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT fk_training_plans_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE training_plan_exercises (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_name varchar(50) NOT NULL,
    day_number integer NOT NULL,
    exercise_name varchar(100) NOT NULL,
    max_reps integer NOT NULL,
    min_reps integer NOT NULL,
    position integer NOT NULL,
    target_rir integer NOT NULL,
    target_sets integer NOT NULL,
    training_plan_id bigint NOT NULL,
    CONSTRAINT fk_training_plan_exercises_plan
        FOREIGN KEY (training_plan_id) REFERENCES training_plans (id)
);

CREATE INDEX idx_plan_exercises_plan_day
    ON training_plan_exercises (training_plan_id, day_number);

CREATE TABLE workouts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    workout_date date NOT NULL,
    workout_type varchar(50) NOT NULL,
    training_plan_id bigint,
    user_id bigint NOT NULL,
    CONSTRAINT fk_workouts_training_plan FOREIGN KEY (training_plan_id) REFERENCES training_plans (id),
    CONSTRAINT fk_workouts_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_workouts_user_date ON workouts (user_id, workout_date);

CREATE TABLE workout_sets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_name varchar(100) NOT NULL,
    reps integer NOT NULL,
    rir integer NOT NULL,
    set_number integer NOT NULL,
    weight_kg numeric(7, 2) NOT NULL,
    workout_id bigint NOT NULL,
    CONSTRAINT fk_workout_sets_workout FOREIGN KEY (workout_id) REFERENCES workouts (id)
);

CREATE INDEX idx_workout_sets_workout ON workout_sets (workout_id);
